"use client";

import { useState } from "react";
import axios from "axios";
import { FileText, Loader2, Leaf, Recycle, Shield } from "lucide-react";
import { Button } from "@nextui-org/react";

/**
 * ImpactReport — Feature 1B (Generative AI — RAG-style)
 * Generates a personalized impact certificate grounded in actual DB impact data.
 */
export default function ImpactReport({ listing }) {
  const [loading, setLoading] = useState(false);
  const [report, setReport] = useState(null);
  const [error, setError] = useState("");

  const generate = async () => {
    setLoading(true);
    setError("");
    setReport(null);
    try {
      const res = await axios.post("/api/ai/impact-report", { listingId: listing._id });
      setReport(res.data);
    } catch (err) {
      setError(err.response?.data?.message || "Could not generate impact report.");
    } finally {
      setLoading(false);
    }
  };

  const printReport = () => {
    const win = window.open("", "_blank");
    win.document.write(`
      <html>
        <head>
          <title>eWasteMart Impact Certificate</title>
          <style>
            body { font-family: Georgia, serif; max-width: 700px; margin: 60px auto; color: #1a1a1a; }
            h1 { color: #16a34a; font-size: 28px; border-bottom: 3px solid #16a34a; padding-bottom: 12px; }
            h2 { font-size: 16px; color: #666; font-weight: normal; margin-top: -8px; }
            .metrics { display: flex; gap: 24px; margin: 24px 0; }
            .metric { background: #f0fdf4; border: 1px solid #bbf7d0; padding: 16px; border-radius: 8px; flex: 1; text-align: center; }
            .metric-val { font-size: 22px; font-weight: bold; color: #16a34a; }
            .metric-label { font-size: 12px; color: #666; margin-top: 4px; }
            .report-text { line-height: 1.9; font-size: 15px; }
            .footer { margin-top: 40px; padding-top: 16px; border-top: 1px solid #eee; font-size: 12px; color: #999; }
          </style>
        </head>
        <body>
          <h1>🌱 Environmental Impact Certificate</h1>
          <h2>${report.listingTitle}</h2>
          <div class="metrics">
            <div class="metric"><div class="metric-val">${report.impact.co2SavedKg} kg</div><div class="metric-label">CO₂ Saved</div></div>
            <div class="metric"><div class="metric-val">${report.impact.metalsRecoveredKg} kg</div><div class="metric-label">Metals Recovered</div></div>
            <div class="metric"><div class="metric-val">${report.impact.toxinsDivertedKg} kg</div><div class="metric-label">Toxins Diverted</div></div>
          </div>
          <div class="report-text">${report.report.replace(/\n\n/g, "<br/><br/>")}</div>
          <div class="footer">Generated by eWasteMart AI | ${new Date(report.generatedAt).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" })}</div>
        </body>
      </html>
    `);
    win.document.close();
    win.print();
  };

  return (
    <div className="mt-4">
      {!report && (
        <Button
          onPress={generate}
          isLoading={loading}
          size="sm"
          variant="flat"
          className="bg-green-50 text-green-700 font-semibold hover:bg-green-100 dark:bg-green-900/30 dark:text-green-400"
          startContent={!loading && <FileText className="h-3.5 w-3.5" />}
        >
          {loading ? "Generating AI Report..." : "📄 Generate Impact Certificate"}
        </Button>
      )}

      {error && <p className="mt-2 text-xs text-red-600">{error}</p>}

      {report && (
        <div className="mt-3 rounded-xl border border-green-200 bg-green-50 p-5 dark:border-green-900 dark:bg-green-950/30">
          <div className="flex items-center justify-between mb-3">
            <div className="flex items-center gap-2">
              <Leaf className="h-4 w-4 text-green-600" />
              <span className="font-semibold text-green-800 dark:text-green-300 text-sm">
                🌱 Environmental Impact Certificate
              </span>
              <span className="rounded-full bg-green-100 px-2 py-0.5 text-[10px] font-bold uppercase text-green-700 dark:bg-green-900 dark:text-green-400">
                Gen AI (RAG)
              </span>
            </div>
            <Button size="sm" variant="flat" onPress={printReport} className="text-xs">
              Download PDF
            </Button>
          </div>

          <div className="mb-4 grid grid-cols-3 gap-2 text-center">
            <div className="rounded-lg bg-white p-3 dark:bg-gray-900">
              <div className="text-lg font-bold text-green-700 dark:text-green-400">{report.impact.co2SavedKg} kg</div>
              <div className="text-xs text-gray-500">CO₂ Saved</div>
            </div>
            <div className="rounded-lg bg-white p-3 dark:bg-gray-900">
              <div className="text-lg font-bold text-blue-700 dark:text-blue-400">{report.impact.metalsRecoveredKg} kg</div>
              <div className="text-xs text-gray-500">Metals Recovered</div>
            </div>
            <div className="rounded-lg bg-white p-3 dark:bg-gray-900">
              <div className="text-lg font-bold text-amber-700 dark:text-amber-400">{report.impact.toxinsDivertedKg} kg</div>
              <div className="text-xs text-gray-500">Toxins Diverted</div>
            </div>
          </div>

          <p className="text-sm text-green-900 dark:text-green-200 leading-relaxed whitespace-pre-line">
            {report.report}
          </p>

          <p className="mt-3 text-xs text-green-600 dark:text-green-500">
            AI-generated from verified transaction data • {new Date(report.generatedAt).toLocaleDateString("en-IN")}
          </p>
        </div>
      )}
    </div>
  );
}
